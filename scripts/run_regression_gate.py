#!/usr/bin/env python3
"""Regression gate: once a contract is pinned, does a later change that breaks it get blocked?

The contract benchmark asks whether a defect can be refuted and its fix
proven. This report reads the same committed results as a pull-request gate.
The contract was pinned when the fixed function landed. Two later changes are
reviewed against it for every case:

  regression  the change turns the fixed function back into the buggy one;
              the gate should block it.
  keep        the change leaves the fixed function as it is (or re-applies
              the fix); the gate should let it through.

Each arm is a gate:

  mumei       the hand-written port of the changed function is verified
              under the pinned contract. Refuted blocks, proven passes.
  mumei-llm   the LLM ports the changed function to Mumei under the pinned
              header and mumei decides. This is the gate a team could run
              without hand-writing ports.
  llm         the LLM reviews the changed function against the requirement
              and the pinned header and answers holds/violated.

An inconclusive answer (no body, a type error, a timeout, a failed request)
neither blocks nor passes: the change needs a human. A gate is flaky on a
case when its runs give different answers for the same change.

The first-order mutants from scripts/run_mutation_control.py are further
regressions of the fixed ports; the share mumei refutes shows how much of an
arbitrary small change the pinned contract catches, not only the planted
defect.

The report is derived offline from proofs/results/*.json and
proofs/mutation.json (no Mumei, no model calls). `--check` fails when
proofs/REGRESSION.md is out of date.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import run_contract_bench as cb  # noqa: E402

REPORT = cb.PROOFS_ROOT / "REGRESSION.md"
MUTATION = cb.PROOFS_ROOT / "mutation.json"
GATES = ("mumei", "mumei-llm", "llm")
GATE_LABEL = {"mumei": "mumei (hand-written ports)", "mumei-llm": "mumei + LLM port",
              "llm": "LLM review"}
DECISION = {"refuted": "block", "proven": "pass"}


def decision(record: dict, variant: str) -> str:
    return DECISION.get(record[variant]["outcome"], "unresolved")


def gate_runs(doc: dict) -> list[dict]:
    """Per run: regressions blocked/passed/unresolved and kept fixes passed/blocked/unresolved."""
    out = []
    for run in doc["runs"]:
        s = {"cases": len(run)}
        for r in run:
            for change, variant in (("regression", "buggy"), ("keep", "fixed")):
                key = f"{change}_{decision(r, variant)}"
                s[key] = s.get(key, 0) + 1
        out.append(s)
    return out


def flaky_cases(doc: dict) -> list[str]:
    seen: dict[str, dict[str, set]] = {}
    for run in doc["runs"]:
        for r in run:
            per = seen.setdefault(r["id"], {v: set() for v in cb.VARIANTS})
            for v in cb.VARIANTS:
                per[v].add(decision(r, v))
    return sorted(i for i, per in seen.items() if any(len(s) > 1 for s in per.values()))


def gate_row(doc: dict) -> dict:
    runs = gate_runs(doc)
    keys = [f"{c}_{d}" for c in ("regression", "keep") for d in ("block", "pass", "unresolved")]
    row = {"arm": doc["arm"], "model": doc.get("model"), "runs": len(runs), "cases": runs[0]["cases"] if runs else 0}
    for k in keys:
        vals = [s.get(k, 0) for s in runs]
        row[k] = cb.median(vals)
        row[k + "_range"] = (min(vals), max(vals))
    row["flaky"] = flaky_cases(doc)
    usage = cb.usage_total([r for run in doc["runs"] for r in run])
    row["cost_per_pass"] = round(usage["cost_usd"] / len(runs), 4) if runs and doc["arm"] != "mumei" else 0.0
    row["model_seconds_per_pass"] = round(usage["model_seconds"] / len(runs), 1) if runs else 0.0
    return row


def mutation_summary(doc: dict | None) -> dict | None:
    if not doc:
        return None
    counts = {"killed": 0, "survived": 0, "invalid": 0}
    for c in doc["cases"]:
        for m in c["mutants"]:
            if m.get("outcome") in counts:
                counts[m["outcome"]] += 1
    scored = counts["killed"] + counts["survived"]
    counts["score"] = round(100 * counts["killed"] / scored) if scored else 0
    return counts


def fmt(row: dict, key: str) -> str:
    return cb.fmt(row, key)


def render(results: list[dict], mutation: dict | None) -> str:
    rows = [gate_row(d) for a in GATES for d in results if d["arm"] == a]
    cases = rows[0]["cases"] if rows else 0
    out = ["# Regression gate", "",
           "<!-- Generated by scripts/run_regression_gate.py; do not edit by hand. -->", "",
           f"The {cases} contract-benchmark cases read as a pull-request gate. The contract was pinned when the "
           "fixed function landed. A later change either turns the function back into the buggy version "
           "(a regression the gate should block) or keeps the fix (a change the gate should let through). "
           "An unresolved answer sends the change to a human. Values are medians over runs, with the range "
           "in brackets; see [RESULTS.md](RESULTS.md) for the per-case answers.", "",
           "| Gate | Model | Runs | Regressions blocked | Regressions let through | Regressions unresolved "
           "| Good changes blocked | Good changes unresolved | Flaky cases | Model cost per gate pass |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        cost = "$0 (no model)" if r["arm"] == "mumei" else f"${r['cost_per_pass']:.2f}"
        flaky = "—" if r["runs"] < 2 else str(len(r["flaky"]))
        out.append(f"| {GATE_LABEL[r['arm']]} | {r['model'] or '—'} | {r['runs']} | {fmt(r, 'regression_block')} "
                   f"| {fmt(r, 'regression_pass')} | {fmt(r, 'regression_unresolved')} | {fmt(r, 'keep_block')} "
                   f"| {fmt(r, 'keep_unresolved')} | {flaky} | {cost} |")
    out += ["",
            "How to read it:", "",
            "- **mumei (hand-written ports)** is the gate once a port exists for the function. The ports were "
            "written with knowledge of the defects, so this row shows what the pinned contracts can enforce, not "
            "detection. mumei is deterministic, so one run is enough; a block comes with a counterexample and a "
            "pass with a proof certificate.",
            "- **mumei + LLM port** is the gate without hand-written ports. The LLM only writes the `.mm` body of "
            "the changed function; mumei decides. A regression let through here is a translation that dropped "
            "the defect, a flaky case is a port that differs between runs.",
            "- **LLM review** answers holds/violated itself. A pass is the model's opinion, not a proof, and the "
            "same change can get a different answer on another run.", ""]
    for r in rows:
        if r["runs"] > 1 and r["flaky"]:
            out.append(f"Flaky under {GATE_LABEL[r['arm']]}: " + ", ".join(f"`{i}`" for i in r["flaky"]) + ".")
            out.append("")
    if mutation:
        scored = mutation["killed"] + mutation["survived"]
        out += ["## Beyond the planted defect", "",
                f"[MUTATION.md](MUTATION.md) makes first-order mutants of the fixed ports (relational, logical, "
                f"arithmetic and constant changes) and verifies them under the pinned contracts. mumei blocks "
                f"{mutation['killed']} of {scored} scored mutants ({mutation['score']}%); "
                f"{mutation['survived']} pass, either because the contract does not constrain that part of the "
                f"body or because the mutant is equivalent. {mutation['invalid']} do not verify either way. "
                "A pinned contract only gates what it states: the planted-defect rows above are an upper bound "
                "for an arbitrary later change.", ""]
    return "\n".join(out)


def load_mutation() -> dict | None:
    return mutation_summary(json.loads(MUTATION.read_text())) if MUTATION.is_file() else None


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--check", action="store_true", help="fail when proofs/REGRESSION.md is out of date")
    return p


def main(argv: list[str]) -> int:
    args = build_parser().parse_args(argv)
    text = render(cb.load_results(), load_mutation())
    if args.check:
        if not REPORT.is_file() or REPORT.read_text() != text:
            print(f"error: {REPORT.relative_to(cb.REPO_ROOT)} is out of date; run scripts/run_regression_gate.py",
                  file=sys.stderr)
            return 1
        print("REGRESSION.md is up to date")
        return 0
    REPORT.write_text(text)
    print(f"wrote {REPORT.relative_to(cb.REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
